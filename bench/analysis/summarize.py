"""Build the result tables of the report from the run directories and print them (Markdown).

Main table: d3-flash vs the same-backbone control (Qwen3.5-9B, identical prompt and readout) vs d3 without the image,
per benchmark (question-weighted accuracy over a run's slices; ECE). Robustness and ablation tables are computed
from raw results restricted to the exact same items as their reference run.

    python -m bench.analysis.summarize
"""

from __future__ import annotations

import glob
import json
import math
from collections import defaultdict
from pathlib import Path

import numpy as np

from bench.common import CONVERTED, RUNS, read_jsonl
from bench.metrics.score import ece, question_records

A = CONVERTED / "ablations"

# label, run subdir, score file (by), rows file for raw recomputation
MAIN = [
    ("Scene classification (6 sets, full class list)", "scene_nway", "benchmark"),
    ("GEOBench-VLM", "geobench_vlm", "benchmark"),
    ("LHRS-Bench (single order, 4 rotations pooled)", "lhrs_bench", "benchmark"),
    ("CHOICE", "choice", "level1"),
    ("VRSBench-VQA-MC", "vrsbench_vqa_mc", "task_family"),
    ("RSVQA-LR", "rsvqa_lr", "task_family"),
    ("RSVQA-HR test-2", "rsvqa_hr", "task_family"),
    ("BigEarthNet v2 (19 yes/no per image)", "bigearthnet", "benchmark"),
    ("EarthMind-Bench optical", "earthmind_optical", "benchmark"),
    ("EarthMind-Bench SAR", "earthmind_sar", "benchmark"),
    ("EarthMind-Bench fused", "earthmind_fused", "benchmark"),
    ("CDVQA test-2", "cdvqa", "task_family"),
    ("xBD building damage (4 levels)", "xbd_damage", "benchmark"),
    ("xBD disaster type", "xbd_type", "benchmark"),
    ("DisasterM3", "disasterm3", "task_family"),
    ("DVL-Bench", "dvl", "task_family"),
    ("XLRS-Bench-lite (downscaled)", "xlrs_v0", "benchmark"),
    ("XLRS-Bench-lite (overview + quadrants)", "xlrs_v1", "benchmark"),
    ("fMoW-WILDS OOD (region / country / land use)", "fmow_wilds", "qid"),
    ("UrBench geo-localization", "urbench_geo", "task_family"),
    ("VHM-HnstD honesty probes", "vhm_hnstd", "task_family"),
]


def overall(path: Path) -> dict | None:
    if not path.exists():
        return None
    s = json.load(open(path))["slices"]
    n = sum(v["n"] for v in s.values())
    if not n:
        return None
    return {"n": n, "acc": sum(v["accuracy"] * v["n"] for v in s.values()) / n,
            "ece": sum(v["ece"] * v["n"] for v in s.values()) / n, "errors": json.load(open(path))["question_errors"]}


def fmt(x, pct=True):
    return "—" if x is None else (f"{x * 100:.1f}" if pct else f"{x:.3f}")


def recs_for(rows_path: Path, run_dir: Path) -> list[dict]:
    rows = {r["id"]: r for r in read_jsonl(rows_path)}
    latest = {}
    for f in glob.glob(f"{run_dir}/chunk*.jsonl") + glob.glob(f"{run_dir}/retry/chunk*.jsonl"):
        for r in read_jsonl(f):
            if r["id"] not in latest or r.get("status") == "ok":
                latest[r["id"]] = r
    return question_records(rows, list(latest.values()))[0]


def acc_on(recs: list[dict], ids: set[str] | None = None, strip: str = "") -> tuple[float, float, int]:
    sel = [r for r in recs if ids is None or r["id"].removesuffix(strip) in ids]
    if not sel:
        return float("nan"), float("nan"), 0
    c = np.array([r["correct"] for r in sel], float)
    return float(c.mean()), ece(np.array([r["conf"] for r in sel]), c), len(sel)


def main() -> None:
    lines = ["# Summary tables (generated by `python -m bench.analysis.summarize`)", ""]
    lines += ["## Main: d3-flash vs Qwen3.5-9B (same prompt and readout) vs d3-flash without the image", "",
              "| Benchmark | Questions | d3-flash | Qwen3.5-9B | Δ | d3, no image | ECE d3 / Qwen |",
              "|---|---:|---:|---:|---:|---:|---|"]
    for label, sub, by in MAIN:
        d = overall(RUNS / "d3" / sub / f"score_{by}.json")
        q = overall(RUNS / "qwen3.5-9b" / sub / f"score_{by}.json")
        b = overall(RUNS / "d3_blind" / sub / f"score_{by}.json")
        if not d:
            continue
        delta = f"{(d['acc'] - q['acc']) * 100:+.1f}" if q else "—"
        lines.append(f"| {label} | {d['n']:,} | {fmt(d['acc'])} | {fmt(q and q['acc'])} | {delta} | "
                     f"{fmt(b and b['acc'])} | {fmt(d['ece'], False)} / {fmt(q and q['ece'], False)} |")
    lines += ["", "Accuracy is question-weighted over each run's slices; for yes/no questions it is accuracy at p = 0.5.", ""]

    # Robustness: option permutations.
    lines += ["## Robustness: option order (3 seeded permutations per item, 1,000-item subsets)", "",
              "| Subset | Model | Accuracy (first order) | All 3 orders correct | Items whose answer changes |",
              "|---|---|---:|---:|---:|"]
    for subset in ("scene", "geobench"):
        for model in ("d3", "qwen3.5-9b"):
            p = RUNS / "robust" / model / f"{subset}_perm3" / "score_benchmark.json"
            if not p.exists():
                continue
            for name, s in json.load(open(p))["slices"].items():
                c = s.get("consistency")
                if c:
                    lines.append(f"| {subset} / {name} | {model} | {fmt(c['first_variant'])} | {fmt(c['all_variants_correct'])} | "
                                 f"{fmt(c['answer_flip_rate'])} |")

    # Robustness: rotations / flips (d3), all on the same 1,000 + 1,000 items as the original runs.
    lines += ["", "## Robustness: image rotation / flip (d3-flash; same items)", "",
              "| Subset | Original | rot90 | rot180 | rot270 | hflip | Correct under all 4 rotations (0/90/180/270) |",
              "|---|---:|---:|---:|---:|---:|---:|"]
    for subset, rows_file, ref_sub, ref_rows in (("scene", A / "scene_sub1k.jsonl", "scene_nway", CONVERTED / "scene/scene_all.jsonl"),
                                                 ("geobench", A / "geobench_sub1k.jsonl", "geobench_vlm", CONVERTED / "geobench_vlm/geobench_vlm_single.jsonl")):
        ids = {r["id"] for r in read_jsonl(rows_file)}
        ref = [r for r in recs_for(ref_rows, RUNS / "d3" / ref_sub) if r["id"] in ids]
        cells, by_rot = [fmt(acc_on(ref)[0])], {"rot0": {r["id"]: r["correct"] for r in ref}}
        for t in ("rot90", "rot180", "rot270", "hflip"):
            rr = recs_for(rows_file, RUNS / "robust" / "d3" / f"{subset}_{t}")
            cells.append(fmt(acc_on(rr)[0]) if rr else "—")
            by_rot[t] = {r["id"]: r["correct"] for r in rr}
        common = set.intersection(*(set(by_rot[k]) for k in ("rot0", "rot90", "rot180", "rot270"))) if all(by_rot.get(k) for k in ("rot90", "rot180", "rot270")) else set()
        allrot = np.mean([all(by_rot[k][i] for k in ("rot0", "rot90", "rot180", "rot270")) for i in common]) if common else None
        lines.append(f"| {subset} | " + " | ".join(cells) + f" | {fmt(allrot)} |")

    # Ablations.
    lines += ["", "## Ablations (d3-flash; same items as the reference)", "", "| Ablation | Reference | Variant | Δ |", "|---|---:|---:|---:|"]
    for subset, rows_file, ref_sub, ref_rows in (("scene", A / "scene_sub1k.jsonl", "scene_nway", CONVERTED / "scene/scene_all.jsonl"),
                                                 ("geobench", A / "geobench_sub1k.jsonl", "geobench_vlm", CONVERTED / "geobench_vlm/geobench_vlm_single.jsonl")):
        ids = {r["id"] for r in read_jsonl(rows_file)}
        ref_acc = acc_on([r for r in recs_for(ref_rows, RUNS / "d3" / ref_sub) if r["id"] in ids])[0]
        for t, label in (("down2", "A1 resolution ½"), ("down4", "A1 resolution ¼"), ("permavg", "A6 permutation averaging")):
            rr = recs_for(rows_file, RUNS / "ablation" / "d3" / f"{subset}_{t}")
            if rr:
                a = acc_on(rr)[0]
                lines.append(f"| {subset}: {label} | {fmt(ref_acc)} | {fmt(a)} | {(a - ref_acc) * 100:+.1f} |")
    # A2 metadata state.
    scene_ids = {r["id"] for r in read_jsonl(A / "scene_sub1k.jsonl")}
    ref = acc_on([r for r in recs_for(CONVERTED / "scene/scene_all.jsonl", RUNS / "d3" / "scene_nway") if r["id"] in scene_ids])[0]
    st = recs_for(A / "scene_sub1k_state.jsonl", RUNS / "ablation" / "d3" / "scene_state")
    if st:
        a = acc_on(st)[0]
        lines.append(f"| scene: A2 sensor + GSD in state | {fmt(ref)} | {fmt(a)} | {(a - ref) * 100:+.1f} |")
    for name, path in (("reference", RUNS / "d3" / "bigearthnet" / "score_benchmark.json"),
                       ("state", RUNS / "ablation" / "d3" / "bigearthnet_state" / "score_benchmark.json")):
        if path.exists():
            s = next(iter(json.load(open(path))["slices"].values()))
            if name == "reference":
                ben_ref = s
            else:
                lines.append(f"| BigEarthNet: A2 sensor, GSD, country, date in state (micro-F1 / mAP) | "
                             f"{ben_ref['multilabel']['micro_f1']:.3f} / {ben_ref['multilabel']['macro_map']:.3f} | "
                             f"{s['multilabel']['micro_f1']:.3f} / {s['multilabel']['macro_map']:.3f} | "
                             f"{s['multilabel']['micro_f1'] - ben_ref['multilabel']['micro_f1']:+.3f} / "
                             f"{s['multilabel']['macro_map'] - ben_ref['multilabel']['macro_map']:+.3f} |")
    # A5 option count on the AID + NWPU subset.
    many = {r["id"] for r in read_jsonl(A / "scene_manyclass_sub.jsonl")}
    ref = acc_on([r for r in recs_for(CONVERTED / "scene/scene_all.jsonl", RUNS / "d3" / "scene_nway") if r["id"] in many])[0]
    for k in (4, 8, 16):
        rr = recs_for(A / f"scene_manyclass_{k}way.jsonl", RUNS / "ablation" / "d3" / f"scene_{k}way")
        if rr:
            a = acc_on(rr)[0]
            lines.append(f"| AID + NWPU (460 items): A5 {k} options vs full list (30 / 45) | {fmt(ref)} | {fmt(a)} | {(a - ref) * 100:+.1f} |")

    print("\n".join(lines))


if __name__ == "__main__":
    main()
